"""기상청 단기예보 격자를 공식 변환상수로 경위도 대표좌표로 역변환한다."""

from __future__ import annotations

import math


def 격자에서_경위도(가로: float, 세로: float) -> tuple[float, float]:
    지구반경 = 6371.00877
    격자간격 = 5.0
    표준위도1 = 30.0
    표준위도2 = 60.0
    기준경도 = 126.0
    기준위도 = 38.0
    기준가로 = 43.0
    기준세로 = 136.0
    도라디안 = math.pi / 180.0

    환산반경 = 지구반경 / 격자간격
    위도1 = 표준위도1 * 도라디안
    위도2 = 표준위도2 * 도라디안
    경도0 = 기준경도 * 도라디안
    위도0 = 기준위도 * 도라디안
    원뿔상수 = math.log(math.cos(위도1) / math.cos(위도2)) / math.log(
        math.tan(math.pi * 0.25 + 위도2 * 0.5)
        / math.tan(math.pi * 0.25 + 위도1 * 0.5)
    )
    축척상수 = (
        math.tan(math.pi * 0.25 + 위도1 * 0.5) ** 원뿔상수
        * math.cos(위도1)
        / 원뿔상수
    )
    기준거리 = 환산반경 * 축척상수 / (
        math.tan(math.pi * 0.25 + 위도0 * 0.5) ** 원뿔상수
    )

    가로차 = 가로 - 기준가로
    세로차 = 기준거리 - (세로 - 기준세로)
    거리 = math.sqrt(가로차**2 + 세로차**2)
    위도 = 2.0 * math.atan((환산반경 * 축척상수 / 거리) ** (1.0 / 원뿔상수)) - math.pi * 0.5
    각도 = math.atan2(가로차, 세로차)
    경도 = 각도 / 원뿔상수 + 경도0
    return 위도 / 도라디안, 경도 / 도라디안


if __name__ == "__main__":
    위도, 경도 = 격자에서_경위도(58, 74)
    print(f"기상청 격자 (58, 74) 대표좌표: 위도 {위도:.8f}, 경도 {경도:.8f}")
